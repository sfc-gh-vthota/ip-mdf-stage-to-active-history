-- IP-Metadata-Driven-Framework : 05 - task graph (DAG)
--   TSK_FW_ROOT        every 5 min, only when ANY stage stream has data (no compute otherwise)
--     ├─ TSK_FW_LOAD_INCIDENT        WHEN its stream has data -> CALL SP_FW_LOAD(1)
--     ├─ TSK_FW_LOAD_PROBLEM         ...                       -> CALL SP_FW_LOAD(2)
--     ├─ TSK_FW_LOAD_CHANGE_REQUEST  ...                       -> CALL SP_FW_LOAD(3)
--     ├─ TSK_FW_LOAD_SC_REQ_ITEM     ...                       -> CALL SP_FW_LOAD(4)
--     └─ TSK_FW_LOAD_SYS_USER        ...                       -> CALL SP_FW_LOAD(5)
--   TSK_FW_FINALIZER   after every graph run: one summary row in FW_GRAPH_RUNS
-- Children run in parallel; each entity commits (or rolls back) independently.
USE ROLE SYSADMIN;
USE SCHEMA IP_METADATA_FW.CONTROL;

CREATE TABLE IF NOT EXISTS IP_METADATA_FW.CONTROL.FW_GRAPH_RUNS (
    GRAPH_RUN_GROUP_ID  VARCHAR(64),
    FINALIZED_AT        TIMESTAMP_NTZ,
    ENTITIES_LOADED     NUMBER,
    ENTITIES_NO_DATA    NUMBER,
    ENTITIES_FAILED     NUMBER,
    ROWS_READ           NUMBER,
    SUMMARY             VARIANT
);

-- Suspend the root before (re)defining children (no-op on first run)
ALTER TASK IF EXISTS TSK_FW_ROOT SUSPEND;

CREATE OR REPLACE TASK TSK_FW_ROOT
    WAREHOUSE = IP_MDF_LOAD_WH
    SCHEDULE = '5 MINUTE'
    OVERLAP_POLICY = NO_OVERLAP
    SUSPEND_TASK_AFTER_NUM_FAILURES = 10
    COMMENT = 'IP-Metadata-Driven-Framework: root, fires only when a stage stream has data'
WHEN
    SYSTEM$STREAM_HAS_DATA('IP_METADATA_FW.RAW_INSERT.INCIDENT_FW_STRM')
 OR SYSTEM$STREAM_HAS_DATA('IP_METADATA_FW.RAW_INSERT.PROBLEM_FW_STRM')
 OR SYSTEM$STREAM_HAS_DATA('IP_METADATA_FW.RAW_INSERT.CHANGE_REQUEST_FW_STRM')
 OR SYSTEM$STREAM_HAS_DATA('IP_METADATA_FW.RAW_INSERT.SC_REQ_ITEM_FW_STRM')
 OR SYSTEM$STREAM_HAS_DATA('IP_METADATA_FW.RAW_INSERT.SYS_USER_FW_STRM')
AS
    SELECT 'IP-MDF graph run started';

CREATE OR REPLACE TASK TSK_FW_LOAD_INCIDENT
    WAREHOUSE = IP_MDF_LOAD_WH AFTER TSK_FW_ROOT
    WHEN SYSTEM$STREAM_HAS_DATA('IP_METADATA_FW.RAW_INSERT.INCIDENT_FW_STRM')
AS CALL IP_METADATA_FW.CONTROL.SP_FW_LOAD(1);

CREATE OR REPLACE TASK TSK_FW_LOAD_PROBLEM
    WAREHOUSE = IP_MDF_LOAD_WH AFTER TSK_FW_ROOT
    WHEN SYSTEM$STREAM_HAS_DATA('IP_METADATA_FW.RAW_INSERT.PROBLEM_FW_STRM')
AS CALL IP_METADATA_FW.CONTROL.SP_FW_LOAD(2);

CREATE OR REPLACE TASK TSK_FW_LOAD_CHANGE_REQUEST
    WAREHOUSE = IP_MDF_LOAD_WH AFTER TSK_FW_ROOT
    WHEN SYSTEM$STREAM_HAS_DATA('IP_METADATA_FW.RAW_INSERT.CHANGE_REQUEST_FW_STRM')
AS CALL IP_METADATA_FW.CONTROL.SP_FW_LOAD(3);

CREATE OR REPLACE TASK TSK_FW_LOAD_SC_REQ_ITEM
    WAREHOUSE = IP_MDF_LOAD_WH AFTER TSK_FW_ROOT
    WHEN SYSTEM$STREAM_HAS_DATA('IP_METADATA_FW.RAW_INSERT.SC_REQ_ITEM_FW_STRM')
AS CALL IP_METADATA_FW.CONTROL.SP_FW_LOAD(4);

CREATE OR REPLACE TASK TSK_FW_LOAD_SYS_USER
    WAREHOUSE = IP_MDF_LOAD_WH AFTER TSK_FW_ROOT
    WHEN SYSTEM$STREAM_HAS_DATA('IP_METADATA_FW.RAW_INSERT.SYS_USER_FW_STRM')
AS CALL IP_METADATA_FW.CONTROL.SP_FW_LOAD(5);

-- Finalizer: summarise this graph run from the framework audit (runs even if a child failed)
CREATE OR REPLACE TASK TSK_FW_FINALIZER
    WAREHOUSE = IP_MDF_LOAD_WH
    FINALIZE = TSK_FW_ROOT
AS
EXECUTE IMMEDIATE
$$
BEGIN
    LET v_gid VARCHAR := SYSTEM$TASK_RUNTIME_INFO('CURRENT_TASK_GRAPH_RUN_GROUP_ID');
    LET v_start TIMESTAMP_NTZ := SYSTEM$TASK_RUNTIME_INFO('CURRENT_TASK_GRAPH_ORIGINAL_SCHEDULED_TIMESTAMP')::TIMESTAMP_LTZ::TIMESTAMP_NTZ;
    INSERT INTO IP_METADATA_FW.CONTROL.FW_GRAPH_RUNS
    SELECT :v_gid, SYSDATE(),
           COUNT_IF(STATUS = 'SUCCESS'), COUNT_IF(STATUS = 'NO_DATA'), COUNT_IF(STATUS = 'FAILED'),
           SUM(ROWS_READ),
           ARRAY_AGG(OBJECT_CONSTRUCT('entity', ENTITY_NAME, 'status', STATUS, 'rows_read', ROWS_READ,
                                      'active_ins', ACTIVE_INSERTED, 'active_upd', ACTIVE_UPDATED,
                                      'hist_ins', HIST_INSERTED, 'failed_step', FAILED_STEP))
    FROM IP_METADATA_FW.CONTROL.FW_RUN_AUDIT
    WHERE TRIGGERED_BY ILIKE '%TSK_FW_LOAD_%' AND START_TS >= DATEADD(minute, -1, :v_start);
END;
$$;

-- Resume children + finalizer first, root last (all in one call)
SELECT SYSTEM$TASK_DEPENDENTS_ENABLE('IP_METADATA_FW.CONTROL.TSK_FW_ROOT');

SHOW TASKS LIKE 'TSK_FW_%' IN SCHEMA IP_METADATA_FW.CONTROL;
