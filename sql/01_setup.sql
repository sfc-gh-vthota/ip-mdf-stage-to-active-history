-- IP-Metadata-Driven-Framework : 01 - database, schemas, warehouse and sample stage tables
--   RAW_INSERT : insert-only stage tables (writers only INSERT, so they never block each other)
--   CORE       : ACTIVE (latest per key) and HISTORY (SCD2) tables, created by SP_FW_ONBOARD
--   CONTROL    : mapping table, audit tables, procedures and tasks
-- The 5 ServiceNow tables below are samples. Replace them with your own stage tables.
USE ROLE SYSADMIN;

CREATE DATABASE IF NOT EXISTS IP_METADATA_FW;
CREATE SCHEMA IF NOT EXISTS IP_METADATA_FW.RAW_INSERT COMMENT = 'Insert-only stage tables';
CREATE SCHEMA IF NOT EXISTS IP_METADATA_FW.CONTROL    COMMENT = 'Framework mapping, audit, procedures, tasks';

CREATE WAREHOUSE IF NOT EXISTS IP_MDF_LOAD_WH
  WAREHOUSE_SIZE = 'SMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE COMMENT = 'IP-Metadata-Driven-Framework stage -> ACTIVE/HISTORY loads';
USE WAREHOUSE IP_MDF_LOAD_WH;

-- Sample stage tables (ServiceNow). _BATCH_ID / _LOAD_TS are stage-only columns (see EXCLUDE_COLS).
CREATE TABLE IF NOT EXISTS IP_METADATA_FW.RAW_INSERT.INCIDENT (
    SYS_ID VARCHAR(32) NOT NULL,
    NUMBER VARCHAR(40),
    SHORT_DESCRIPTION VARCHAR(160),
    DESCRIPTION VARCHAR(4000),
    CALLER_ID VARCHAR(32),
    CATEGORY VARCHAR(40),
    SUBCATEGORY VARCHAR(40),
    PRIORITY NUMBER(1,0),
    IMPACT NUMBER(1,0),
    URGENCY NUMBER(1,0),
    STATE NUMBER(2,0),
    ASSIGNMENT_GROUP VARCHAR(32),
    ASSIGNED_TO VARCHAR(32),
    OPENED_AT TIMESTAMP_NTZ,
    ACTIVE BOOLEAN,
    SYS_CREATED_ON TIMESTAMP_NTZ,
    SYS_CREATED_BY VARCHAR(40),
    SYS_UPDATED_ON TIMESTAMP_NTZ,
    SYS_UPDATED_BY VARCHAR(40),
    SYS_MOD_COUNT NUMBER(10,0),
    _BATCH_ID VARCHAR(64),
    _LOAD_TS TIMESTAMP_NTZ DEFAULT SYSDATE()
);

